#include <cstring>
#include <cstdio>

extern "C" { void (*g_spu_host_line_commit_hook)(uint32_t) = nullptr; }
static constexpr uint32_t object_ea = 0x20000, first_base = 0x30000;
static std::atomic<uint32_t> object_base{first_base};
static std::atomic<uint16_t> counters[7];
extern "C" uint32_t vm_read32(uint64_t ea) {
    assert(ea == object_ea + 4); return object_base.load();
}
extern "C" uint16_t vm_read16(uint64_t ea) {
    const uint32_t base = object_base.load();
    assert(ea >= base + 0x12 && ea <= base + 0x1e && !(ea & 1));
    return counters[(ea - base - 0x12) / 2].load();
}
// Generated by test_job_wait.py from the actual production PPU function.
#include "job_wait_lift.inc"

static ppu_context initial() {
    ppu_context context{};
    for (unsigned i = 0; i < 32; ++i) context.gpr[i] = 0x12345678ABC00000ull + i;
    context.gpr[3] = object_ea; context.gpr[4] = 5;
    context.cr = 0x76543210; context.xer = 0x80000000;
    return context;
}
static bool any_watch() {
    for (auto& address : watched) if (address.load()) return true;
    return false;
}
int main() {
    setenv("MOTORSTORM_JOB_EVENT_WAIT", "1", 1);
    motorstorm_job_wait_init();
    assert(g_spu_host_line_commit_hook);
    for (auto& counter : counters) counter.store(5);
    ppu_context expected = initial();
    original_job_wait(&expected);
    ppu_context ready = initial();
    func_00CF7358(&ready);
    assert(!memcmp(&ready, &expected, sizeof(ready)));

    for (int notify = 0; notify < 2; ++notify) {
        for (auto& counter : counters) counter.store(4);
        ppu_context context = initial();
        std::atomic<bool> done{false};
        std::thread waiter([&] { func_00CF7358(&context); done.store(true); });
        const auto deadline = std::chrono::steady_clock::now() + std::chrono::seconds(2);
        while (!any_watch() && std::chrono::steady_clock::now() < deadline)
            std::this_thread::yield();
        assert(any_watch());
        // All lanes except the last completing is insufficient. Unrelated
        // notifications and timeouts must never let the guest escape early.
        for (unsigned i = 0; i < 6; ++i) counters[i].store(5);
        for (int i = 0; i < 20; ++i) {
            g_spu_host_line_commit_hook(first_base + 128);
            std::this_thread::sleep_for(std::chrono::microseconds(100));
            assert(!done.load());
        }
        counters[6].store(5);
        if (notify) g_spu_host_line_commit_hook(first_base);
        while (!done.load() && std::chrono::steady_clock::now() < deadline)
            std::this_thread::yield();
        assert(done.load());
        waiter.join();
        assert(!memcmp(&context, &expected, sizeof(context)));
        assert(!any_watch());
    }
    // A replaced queue pointer and an already-complete queue do not sleep.
    for (auto& counter : counters) counter.store(5);
    motorstorm_job_wait_pause(object_ea, first_base + 128, 5);
    motorstorm_job_wait_pause(object_ea, first_base, 5);
    assert(!any_watch());
    puts("PASS: real lifted wait preserves registers, all seven counters, wakeup, fallback and pointer replacement");
}
